#include "sql/stmt/update_stmt.h"
#include "common/log/log.h"
#include "sql/stmt/filter_stmt.h"
#include "storage/db/db.h"
#include "storage/table/table.h"

UpdateStmt::UpdateStmt(Table *table, FilterStmt *filter_stmt, const FieldMeta *field_meta, const Value &value)
    : table_(table), filter_stmt_(filter_stmt), field_meta_(field_meta), value_(value)
{}

UpdateStmt::~UpdateStmt()
{
  if (nullptr != filter_stmt_) {
    delete filter_stmt_;
    filter_stmt_ = nullptr;
  }
}

RC UpdateStmt::create(Db *db, const UpdateSqlNode &update, Stmt *&stmt)
{
  const char *table_name = update.relation_name.c_str();
  if (nullptr == db || nullptr == table_name) {
    LOG_WARN("invalid argument. db=%p, table_name=%p", db, table_name);
    return RC::INVALID_ARGUMENT;
  }

  // check whether the table exists
  Table *table = db->find_table(table_name);
  if (nullptr == table) {
    LOG_WARN("no such table. db=%s, table_name=%s", db->name(), table_name);
    return RC::SCHEMA_TABLE_NOT_EXIST;
  }

  // check whether the field exists
  const FieldMeta *field_meta = table->table_meta().field(update.attribute_name.c_str());
  if (nullptr == field_meta) {
    LOG_WARN("no such field in table. db=%s, table=%s, field=%s", 
             db->name(), table_name, update.attribute_name.c_str());
    return RC::SCHEMA_FIELD_MISSING;
  }

  // check and convert field type if necessary
  Value final_value = update.value;
  if (field_meta->type() != final_value.attr_type()) {
    Value converted_value;
    RC rc = Value::cast_to(final_value, field_meta->type(), converted_value);
    if (OB_FAIL(rc)) {
      LOG_WARN("failed to cast value. table=%s, field=%s, field type=%d, value type=%d, rc=%s",
               table_name, field_meta->name(), field_meta->type(), final_value.attr_type(), strrc(rc));
      return rc;
    }
    final_value = converted_value;
  }

  // create filter statement
  unordered_map<string, Table *> table_map;
  table_map.insert(pair<string, Table *>(string(table_name), table));

  FilterStmt *filter_stmt = nullptr;
  RC          rc          = FilterStmt::create(
      db, table, &table_map, update.conditions.data(), static_cast<int>(update.conditions.size()), filter_stmt);
  if (rc != RC::SUCCESS) {
    LOG_WARN("failed to create filter statement. rc=%d:%s", rc, strrc(rc));
    return rc;
  }

  stmt = new UpdateStmt(table, filter_stmt, field_meta, final_value);
  return RC::SUCCESS;
}
